const MOVE_CAT_KEY = { m1: "m1", special1: "s1", special2: "s2", special3: "s3", ultimate: "ult" };

export function localChar(lang, character) {
  if (!character) return null;
  const pack = CHARACTER_I18N[lang]?.[character.id];
  if (!pack) return character;
  return {
    ...character,
    displayName: pack.title || character.displayName,
    bio: pack.bio || character.bio,
  };
}

export function localMove(lang, characterId, category, move) {
  const pack = CHARACTER_I18N[lang]?.[characterId]?.moves?.[MOVE_CAT_KEY[category] || category];
  if (!pack) return move;
  return { ...move, name: pack[0] || move.name, desc: pack[1] || move.desc };
}